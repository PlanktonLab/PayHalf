const dictionaries: Record<Lang, Dict> = { 'zh-Hant': zh, en, vi, id };

export const LANG_OPTIONS: { value: Lang; label: string; speech: string }[] = [
  { value: 'zh-Hant', label: '中文', speech: 'zh-TW' },
  { value: 'en', label: 'English', speech: 'en-US' },
  { value: 'vi', label: 'Tiếng Việt', speech: 'vi-VN' },
  { value: 'id', label: 'Indonesia', speech: 'id-ID' }
];

const STORAGE_KEY = 'assist-lang';

const readStoredLang = (): Lang | null => {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    return LANG_OPTIONS.some((item) => item.value === stored) ? (stored as Lang) : null;
  } catch {
    return null;
  }
};

const storedLang = readStoredLang();

/** 使用者自己選過語言之後,就不再被請求裡的預設語言覆蓋 */
const userChose = ref(storedLang !== null);
const lang = ref<Lang>(storedLang ?? 'zh-Hant');

export const useAssistI18n = () => {
  const t = (key: MessageKey, params?: Record<string, string | number>) => {
    let text = dictionaries[lang.value][key] ?? zh[key];
    if (params) {
      Object.entries(params).forEach(([name, value]) => {
        text = text.split(`{${name}}`).join(String(value));
      });
    }
    return text;
  };

  const setLang = (next: Lang, fromUser = true) => {
    lang.value = next;
    if (fromUser) {
      userChose.value = true;
      try {
        window.localStorage.setItem(STORAGE_KEY, next);
      } catch {
        // 無法儲存時忽略,畫面仍可正常使用
      }
    }
  };

  /** 長輩的請求帶有「長輩看得懂的語言」,使用者尚未自己選過時才套用 */
  const applyDefaultLang = (next: Lang) => {
    if (!userChose.value) setLang(next, false);
  };

  const speechLang = () =>
    LANG_OPTIONS.find((item) => item.value === lang.value)?.speech ?? 'zh-TW';

  return { lang, t, setLang, applyDefaultLang, speechLang };
};
